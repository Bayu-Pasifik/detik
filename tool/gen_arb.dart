void main() {
  for (final lang in [0, 1]) {
    final m = <String, dynamic>{'@@locale': lang == 0 ? 'id' : 'en'};
    s.forEach((k, v) {
      m[k] = v[lang];
      final ph = RegExp(r'\{(\w+)\}').allMatches(v[0]).map((x) => x.group(1)!);
      if (ph.isNotEmpty) {
        m['@$k'] = {
          'placeholders': {
            for (final p in ph) p: {'type': 'String'}
          }
        };
      }
    });
    File('lib/l10n/app_${lang == 0 ? 'id' : 'en'}.arb')
        .writeAsStringSync(const JsonEncoder.withIndent('  ').convert(m));
  }
}
